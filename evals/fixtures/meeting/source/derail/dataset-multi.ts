// 脱線判定「大人数・上下関係・速いテンポ」の検証データ（使い捨て・製品コードではない）。
// 想定する使い道: 立場の違う人が多数参加する会議で、上司が無駄話を続けているのに部下が言い出しにくい。
// そこで代わりに「議題に戻りませんか」と促せるか、逆に上司の長い正当な説明や有益な寄り道は邪魔しないか、を見る。
//
// 注意:
// - 合成データで、書いたのは AI、ラベルも私たち（AI）が付けている。実際の会議の書き起こしより整っている。
//   つまりここでも精度は実会議より楽観的になりうる。本当の検証は「実際に録音した会議」でしかできない。
// - 6〜10 人が登場し、1 会話 16〜24 発言。相づち・割り込み・言いかけ・長い上司の独白（100〜200字）・
//   同時進行の脇の会話などを入れて、実際の会議のテンポに近づけた。
// - 8 会話は同じ会話を 約35% / 約65% / 全体 で切った版（id が xxx@35 / xxx@65 / xxx@full）も持つ。
//   切り出しの発言数は round(全体 × 0.35 / 0.65)。ラベルは「その切り方の時点」の状態に付けている。
// - expectedNudge: 声をかけるのが正しい（true）か、黙るのが正しい（false）か。drift/stalled は true、それ以外は false。
//   ambiguous は個別に指定（humanAgreement=split は人間でも割れうる）。
import type { Label, Snippet, Utterance } from "./dataset";

export type Scenario =
  | "boss_drift" // (a) 上司が議題と無関係な話を続ける。周囲は相づち
  | "soft_steer_ignored" // (b) 若手が遠慮がちに戻そうとするが、かぶせられる
  | "boss_long_relevant" // (c) 上司の長い、議題に沿った説明・決定の根拠
  | "boss_useful_tangent" // (d) 上司の短い経験談が議題に効く
  | "deference_loop" // (e) 忖度の応酬で何も決まらない
  | "boss_returns" // (f) 上司が少し脱線して自分で戻る
  | "side_conversations" // (g) 若手二人の脇の雑談と、本筋の議論が並行
  | "on_track_large" // (h) 大人数で、テンポよく決定まで進む
  | "cross_dept_heated"; // (i) 部門間で白熱しているが、議題の中身の議論

export interface Speaker {
  name: string;
  role: string;
}
export type HumanAgreement = "clear" | "split";

export interface MultiSnippet extends Snippet {
  scenario: Scenario;
  speakers: Speaker[];
  humanAgreement: HumanAgreement;
  /** 取るべき行動: true=声をかける / false=黙る */
  expectedNudge: boolean;
  /** 同じ会話を複数点で切ったもののグループ名（切り出しなしの会話は未設定） */
  group?: string;
  cutAt?: number | "full";
  cutPct?: 35 | 65 | 100;
  /** 上司にあたる話者名（いる場合） */
  boss?: string;
  /** その切り出しの中での最長の1発言の文字数 */
  maxTurnChars: number;
  /** 元の会話（全体）の発言数 */
  fullLength: number;
}

type Line = [speaker: string, text: string];
const castOf = (s: string): Speaker[] =>
  s
    .trim()
    .split(/\s+/)
    .map((x) => {
      const [name, role] = x.split(":");
      return { name, role };
    });
const toU = (xs: Line[]): Utterance[] => xs.map(([speaker, text]) => ({ speaker, text }));

function check(id: string, cast: Speaker[], lines: Line[]) {
  const names = new Set(cast.map((c) => c.name));
  for (const [sp] of lines) if (!names.has(sp)) throw new Error(`${id}: 話者 ${sp} が cast にいない`);
}
const speakersIn = (cast: Speaker[], lines: Line[]) => {
  const used = new Set(lines.map((l) => l[0]));
  return cast.filter((c) => used.has(c.name));
};
const maxChars = (lines: Line[]) => Math.max(...lines.map((l) => l[1].length));
const defaultNudge = (label: Label) => label === "drift" || label === "stalled";

interface Spec {
  label: Label;
  agreement: HumanAgreement;
  note: string;
  expectedNudge?: boolean;
}

function single(o: {
  id: string;
  scenario: Scenario;
  agenda: string;
  cast: string;
  lines: Line[];
  spec: Spec;
  boss?: string;
}): MultiSnippet {
  const cast = castOf(o.cast);
  check(o.id, cast, o.lines);
  return {
    id: o.id,
    scenario: o.scenario,
    agenda: o.agenda,
    label: o.spec.label,
    note: o.spec.note,
    humanAgreement: o.spec.agreement,
    expectedNudge: o.spec.expectedNudge ?? defaultNudge(o.spec.label),
    utterances: toU(o.lines),
    speakers: speakersIn(cast, o.lines),
    boss: o.boss,
    maxTurnChars: maxChars(o.lines),
    fullLength: o.lines.length,
  };
}

/** 会話を 約35% / 約65% / 全体 で切った 3 件を作る。expect は切り出しの発言数の期待値（書き間違い防止のための検算）。 */
function grouped(o: {
  group: string;
  scenario: Scenario;
  agenda: string;
  cast: string;
  lines: Line[];
  specs: [Spec, Spec, Spec];
  expect: [number, number];
  boss?: string;
}): MultiSnippet[] {
  const cast = castOf(o.cast);
  check(o.group, cast, o.lines);
  const n = o.lines.length;
  const c35 = Math.round(n * 0.35);
  const c65 = Math.round(n * 0.65);
  if (c35 !== o.expect[0] || c65 !== o.expect[1]) {
    throw new Error(`${o.group}: 切り出し位置が想定と違う（n=${n}, 実際 ${c35}/${c65}, 想定 ${o.expect.join("/")}）`);
  }
  const pts: Array<{ n: number; sfx: string; pct: 35 | 65 | 100; cutAt: number | "full" }> = [
    { n: c35, sfx: "35", pct: 35, cutAt: c35 },
    { n: c65, sfx: "65", pct: 65, cutAt: c65 },
    { n, sfx: "full", pct: 100, cutAt: "full" },
  ];
  return pts.map((p, i) => {
    const part = o.lines.slice(0, p.n);
    const spec = o.specs[i];
    return {
      id: `${o.group}@${p.sfx}`,
      scenario: o.scenario,
      agenda: o.agenda,
      label: spec.label,
      note: spec.note,
      humanAgreement: spec.agreement,
      expectedNudge: spec.expectedNudge ?? defaultNudge(spec.label),
      utterances: toU(part),
      speakers: speakersIn(cast, part),
      group: o.group,
      cutAt: p.cutAt,
      cutPct: p.pct,
      boss: o.boss,
      maxTurnChars: maxChars(part),
      fullLength: n,
    } satisfies MultiSnippet;
  });
}

const clear = (label: Label, note: string, expectedNudge?: boolean): Spec => ({ label, agreement: "clear", note, expectedNudge });
const split = (label: Label, note: string, expectedNudge?: boolean): Spec => ({ label, agreement: "split", note, expectedNudge });

