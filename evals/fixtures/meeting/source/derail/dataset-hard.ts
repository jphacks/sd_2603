//   脱線が少しずつ始まる、脱線から自力で戻る、決定が会話の途中に埋まる、言い換えで繰り返す、などを混ぜた。
// - humanAgreement: 「声をかけるべきか／黙るべきか」について、人間の評価者の意見が揃いそうか（clear）、割れそうか（split）。
//   label が ambiguous のものは、split か、「ラベルは決めにくいが取るべき行動は揃う」clear（その場合 expectedNudge を持つ）。
// - 同じ会話を 4 発言目 / 7 発言目 / 全体 で切った版（id が xxx@4, xxx@7, xxx@full）を8会話ぶん用意した。
//   ラベルは「その切り方の時点」の状態に付けている。リアルタイムで途中から判定したときの挙動を見るため。
import type { Label, Snippet, Utterance } from "./dataset";

export type HumanAgreement = "clear" | "split";
export type Phase = "early" | "mid" | "late";

export interface HardSnippet extends Snippet {
  humanAgreement: HumanAgreement;
  /** 会話全体に対する切り出し位置の目安: 5発言以下=early / 8以下=mid / それ以上=late */
  phase: Phase;
  /** 同じ会話を複数箇所で切ったもののグループ名 */
  group?: string;
  /** グループ内での切り出し位置（発言数）。"full" は全体 */
  cutAt?: number | "full";
  /** label=ambiguous かつ humanAgreement=clear のとき: 取るべき行動（声をかけるべきか）。 */
  expectedNudge?: boolean;
}

type Line = [speaker: string, text: string];
const toU = (xs: Line[]): Utterance[] => xs.map(([speaker, text]) => ({ speaker, text }));
const phaseOf = (n: number): Phase => (n <= 5 ? "early" : n <= 8 ? "mid" : "late");

function one(
  id: string,
  agenda: string,
  label: Label,
  humanAgreement: HumanAgreement,
  note: string,
  all: Line[],
  extra: { expectedNudge?: boolean } = {},
): HardSnippet {
  return { id, agenda, label, humanAgreement, note, phase: phaseOf(all.length), utterances: toU(all), ...extra };
}

interface CutSpec {
  label: Label;
  humanAgreement: HumanAgreement;
  note: string;
}
function cuts(group: string, agenda: string, all: Line[], specs: [CutSpec, CutSpec, CutSpec]): HardSnippet[] {
  const points: Array<number | "full"> = [4, 7, "full"];
  return points.map((p, i) => {
    const n = p === "full" ? all.length : p;
    const suffix = p === "full" ? "full" : String(p);
    return {
      id: `${group}@${suffix}`,
      agenda,
      label: specs[i].label,
      humanAgreement: specs[i].humanAgreement,
      note: specs[i].note,
      phase: phaseOf(n),
      group,
      cutAt: p,
      utterances: toU(all.slice(0, n)),
    };
  });
}

