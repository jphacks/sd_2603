import {readFileSync,writeFileSync,existsSync,mkdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {resolve,dirname} from 'node:path';
import {validateSplitManifest} from './data.mjs';
import {hash} from './core.mjs';
const arg=(k,d)=>process.argv.find(a=>a.startsWith(`--${k}=`))?.slice(k.length+3)??d;
const source='docs/jev-tuning/synthetic-benchmark-v1';
const corePath=resolve(arg('core',`${source}/split-manifest.json`)),extensionPath=resolve(arg('extension',`${source}/extension-split-manifest.json`));
const bytesHash=p=>createHash('sha256').update(readFileSync(p)).digest('hex');
const coreSha=bytesHash(corePath);
if(coreSha!=='22e6dc4a51a95556aba7c65431682d3127a3089e3e6e8f0de0f749f8c8a0aa31')throw new Error('Core500 assignments must remain the originally approved bytes');
const core=JSON.parse(readFileSync(corePath)),extension=JSON.parse(readFileSync(extensionPath));
const expected=JSON.parse(readFileSync(`${source}/extension-spec-hashes.json`))['extension-split-manifest.json'];
const extensionSha=bytesHash(extensionPath);
if(extensionSha!==expected)throw new Error('Extension split differs from its preauthoring declaration');
const merged={version:core.version,groups:[...core.groups,...extension.groups],caseAssignments:[...core.caseAssignments,...extension.caseAssignments],provenance:{coreSha256:coreSha,extensionSha256:extensionSha,note:'Concatenation only; original group/id/split/fold assignments unchanged'}};
validateSplitManifest(merged);
if(merged.groups.length!==200||merged.caseAssignments.length!==1000)throw new Error('Expected core100 families/500 cases plus extension100 families/500 cases');
const out=resolve(arg('out','evals/tuning/runs/synthetic-v1/combined-split-manifest.json'));mkdirSync(dirname(out),{recursive:true});
if(existsSync(out)&&hash(JSON.parse(readFileSync(out)))!==hash(merged))throw new Error('Frozen combined manifest differs; use a new versioned output path');
writeFileSync(out,JSON.stringify(merged,null,2)+'\n');
console.log(JSON.stringify({out,groups:merged.groups.length,cases:merged.caseAssignments.length,sha256:bytesHash(out)},null,2));
